                            <h6 class="text-center fw-bold my-5" id="a-5" data-added-date="08.01.2024">Vierter Teil<span style="display:none"> - </span><br />Disziplinarregelungen</h6>
                            <div id="s-p-25">
                                <h6 class="text-center fw-bold  my-4" id="p-25" data-added-date="20.01.2023">§ 25<span style="display:none"> - </span><br />Disziplinarmaßnahmen</h6>
                                <p class="text-justify">Vorgesetzte dürfen im Sinne der Hierarchie innerhalb der Polizei Disziplinarmaßnahmen
                                    erheben und anordnen. Hierfür wird zwischen dienstlichen und direkten
                                    Disziplinarmaßnahmen unterschieden.</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Dienstliche Disziplinarmaßnahmen stellen Maßnahmen mit dienstlicher Konsequenz dar.
                                            Darunter gelten vor allem die intern geregelten Strafmaße. Sie dürfen nur
                                            durch die Polizeiführung oder eine von dieser beauftragten Person ausgesprochen und
                                            angeordnet werden.</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Direkte Disziplinarmaßnahmen stellen Maßnahmen ohne direkte dienstliche Konsequenz
                                            dar. So wird vereinzeltes Fehlverhalten beispielsweise mit einer Sporteinheit gemaßregelt.
                                            Sie dürfen von jedem Vorgesetzten begründet angeordnet werden.</p>
                                    </dd>
                                </dl>
