                            <h6 class="text-center fw-bold my-5" id="a-1" data-added-date="08.01.2024">Einleitende Vorschrift</h6>
                            <div id="s-p-1">
                                <h6 class="text-center fw-bold  my-4" id="p-1" data-added-date="20.01.2023">§ 1<span style="display:none"> - </span><br />Geltungsbereich</h6>
                                <p class="text-justify">(1) Die Dienstvorschrift gilt nur in diesem Bundesland und ist beschränkt auf jegliche
                                    Institutionen der Landespolizei. In diesem speziellen Fall findet die Dienstvorschrift
                                    Anwendung bei allen der Landespolizeidirektion der Freien Hansestadt Stettbeck zugehörigen
                                    Dienststellen.</p>
                                <p class="text-justify">(2) Die Dienstvorschrift gilt für jeden Polizeivollzugsbeamten des Landes Schleswig-Holstein,
                                    unabhängig von Rang, Funktion, Position oder Aufgabe. Sie ist bindend für jeden
                                    Polizeivollzugsbeamten. Verstöße werden durch die jeweiligen Dienstherren oder
                                    Vorgesetzten geahndet.</p>
                                <p class="text-justify">(3) Diese Vorschrift gilt unabhängig von gerichtlich beschlossenen Anordnungen,
                                    entsprechende Entscheidungen eines Gerichts, z. B. Sonderverordnungen oder
                                    Entscheidungen müssen in Rücksprache mit der Direktionsleitung erneut evaluiert werden.
                                    Entscheidungen eines Oberlandesgerichts sind hiervon ausgeschlossen.</p>
                                <p class="text-justify">(4) Zusätzlich gilt im Rahmen dieser Vorschrift das Polizeigesetz der Bundesrepublik
                                    Deutschland – zuwiderhandelnde Maßnahmen werden ebenfalls durch den Dienstherren
                                    oder Vorgesetzten geahndet.</p>
                                <p class="text-justify">(5) Ein Einzelerlass kann vereinzelte Regelungen dieser Vorschrift ganz oder teilweise
                                    ersetzen oder außer Kraft setzen. Hierfür kann dies zeitlich begrenzt oder unbegrenzt
                                    gelten. Unbegrenzte Erlasse gelten in jedem Fall immer nur bis zum Widerruf.</p>
                            </div>
                            <div id="s-a-2"></div>
                            <h6 class="text-center fw-bold my-5" id="a-2" data-added-date="08.01.2024">Erster Teil<span style="display:none"> - </span><br />Allgemeine- und Verhaltensregelungen</h6>
                            <div id="s-p-2">
                                <h6 class="text-center fw-bold  my-4" id="p-2" data-added-date="20.01.2023">§ 2<span style="display:none"> - </span><br />Dienstliche Grundsätze; Grundbestimmungen</h6>
                                <p class="text-justify">Alle Polizeivollzugsbeamten sind Teil einer Exekutivbehörde (der ausführenden Gewalt). Als
                                    Dienstherr ist der Innenminister des Landes (vertreten durch den leitenden Polizeidirektor und seine ständigen Vertreter, die Polizeidirektoren),
                                    der Träger ist das Land selbst.</p>
                                <p class="text-justify">(1) Polizeivollzugsbeamte sind als Beamte der Erhaltung der öffentlichen Ordnung durch
                                    Gefahrenabwehr zugeordnet. In dieser Funktion muss jeder Polizeivollzugsbeamte zu jeder
                                    Zeit in der Lage sein, diesen zugeordneten Aufgaben nachzukommen.</p>
                                <p class="text-justify">(2) Ein neutrales, hilfsbereites, professionelles und offenes Umgangsbild gegenüber dem
                                    Bürger ist Grundvoraussetzung für jeden dienstlichen Konsens. Es ist Grundlage für alle
                                    polizeiliche Arbeit und vor allem im Bürgerkontakt zwingend anzuwenden.</p>
                                <p class="text-justify">(3) Alle getroffenen Maßnahmen müssen dem Gesetz der Verhältnismäßigkeit entsprechen.
                                    Grundsätzlich sind die Entscheidungen abzuwägen und zu treffen, welche der
                                    Allgemeinheit und dem Einzelnen am wenigsten schaden oder diese(n) beeinträchtigen.</p>
                                <p class="text-justify">(4) Handlungen durch Polizeivollzugsbeamte dürfen unter Beachtung aller Vorgaben gegen die
                                    körperliche Unversehrtheit, Freiheit der Person, Versammlungsfreiheit, Privatsphäre und
                                    Freizügigkeit einzelner Personen oder Personengruppen vorgehen.</p>
                                <p class="text-justify">(5) Die Zuständigkeit der Polizei im Sinne dieser Vorschrift endet mit der nicht polizeilichen
                                    Gefahrenabwehr.</p>
                                <p class="text-justify">(6) Polizeivollzugsbeamte sind zur Ausweisung mittels Dienstausweis gegenüber Bürgern auf
                                    Wunsch dessen verpflichtet.</p>
                                <p class="text-justify">(7) Die Ausweispflicht nach Absatz 6 entfällt in folgenden Fällen:</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Die Einsatzlage erfordert eine sofortige Gefahrenabwehr, die ein Vorzeigen des
                                            Dienstausweises unmöglich macht.</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Es besteht unmittelbare Gefahr für Leib und Leben oder eine solche Gefahr wurde unmittelbar angekündigt.</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">3.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Die Kriminalpolizei erachtet das Vorzeigen im Sinne eines dienstlich relevanten Auftrags für nicht indiziert oder das Vorzeigen würde die Erfüllung des dienstlichen Auftrags behindern oder unmöglich machen.</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">4.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Beamte des Spezialeinsatzkommandos sind in allen Fällen, während der Wahrnehmung ihrer spezifischen Aufgaben, von der Ausweispflicht entbunden.</p>
                                    </dd>
                                </dl>
                                <p class="text-justify">(8) Polizeivollzugsbeamten, welche in einer Partnerschaft oder Liebesbeziehung zueinander stehen, ist es untersagt, gemeinsam ein Streifenfahrzeug zu führen. In einzelnen Fällen kann das Verbot durch die Führung aufgehoben werden, wenn eine dienstliche Bevorteilung ausdrücklich ausgeschlossen ist.</p>
                            </div>
                            <div id="s-p-3">
                                <h6 class="text-center fw-bold  my-4" id="p-3" data-added-date="20.01.2023">§ 3<span style="display:none"> - </span><br />Bürgerkontakt</h6>
                                <p class="text-justify">(1) Dem Bürger ist in jeglicher Situation, egal ob als Täter, Tatverdächtiger, Opfer oder Zeuge
                                    sowie Unbeteiligter, mit Neutralität, Professionalität und Transparenz zu begegnen.</p>
                                <p class="text-justify">(2) Im Kontakt zu Bürgern sind die umgangssprachlichen Werte von „Polizei – Ihr Freund und
                                    Helfer“ nicht nur als Motto, sondern als Maxime zu verstehen.</p>
                                <p class="text-justify">(3) Vor dem Gesetz, als auch vor der Polizei, sind alle Personen gleich und ebenso zu
                                    behandeln. Dabei dürfen weder Ruf noch Rang oder Funktion die Maßnahme
                                    beeinträchtigen.</p>
                                <p class="text-justify">(4) Die Autorität weiterer Kollegen oder Führungspersonen sind im Bürgerkontakt als auch im
                                    Kontakt untereinander nicht zu untergraben oder anzuzweifeln.</p>
                            </div>
                            <div id="s-p-4">
                                <h6 class="text-center fw-bold  my-4" id="p-4" data-added-date="20.01.2023">§ 4<span style="display:none"> - </span><br />Erscheinungsbild; Kleiderordnung</h6>
                                <p class="text-justify">(1) <em>Entfallen.</em>
                                <p class="text-justify">(2) Tätowierungen mit offensichtlichen Gewaltdarstellungen oder Tätowierungen, welche an
                                    der Treue des einzelnen Polizeivollzugsbeamten zweifeln lassen, können zu einer
                                    Auflösung des Beamtenverhältnisses führen.</p>
                                <p class="text-justify">(3) Im Rahmen des Dienstes als auch im Rahmen dieser Vorschrift hat ein
                                    Polizeivollzugsbeamter zu jeder Zeit ein geordnetes Auftreten zu pflegen.</p>
                                <p class="text-justify">(4) Während des Dienstes ist zwingend die für die jeweilige Funktion, den jeweiligen Rang
                                    oder die jeweilige Aufgabe angepasste Dienstuniform zu tragen. Hierbei ist auf
                                    Ordentlichkeit der Uniform zu achten.</p>
                                <p class="text-justify">(5) Vorgegebene Dienstausrüstung (z. B. der Dienstgürtel, die Dienstweste und weitere) sind
                                    nicht grundlos und ohne Genehmigung des Dienstherrn auszutauschen.</p>
                                <p class="text-justify">(6) Beamte der Kriminalpolizei sind von den Vorschriften nach Absatz 1, 4 und 5 zur Erfüllung ihrer besonderen dienstlichen Aufgaben entbunden.</p>
                            </div>
                            <div id="s-a-3"></div>
                            <h6 class="text-center fw-bold my-5" id="a-3" data-added-date="08.01.2024">Zweiter Teil<span style="display:none"> - </span><br />Persönliche Eignung</h6>
                            <div id="s-p-5">
                                <h6 class="text-center fw-bold  my-4" id="p-5" data-added-date="20.01.2023">§ 5<span style="display:none"> - </span><br />Körperliche und seelische Eignung</h6>
                                <p class="text-justify">(1) Jeder Polizeivollzugsbeamte hat im Rahmen seines Dienstes sowie dieser Vorschrift zu jeder
                                    Zeit eine entsprechende körperliche und geistige Gesundheit vor-/aufzuweisen und muss
                                    entsprechend gebildet sein, um den Anforderungen des Dienstes als Polizeivollzugsbeamter
                                    entsprechen zu können.</p>
                                <p class="text-justify">(2) Die Eignung wird durch die Ausbildungsabteilung und Praxisanleiter kontinuierlich geprüft
                                    und evaluiert. Polizeivollzugsbeamte sind auf Aufforderung zur Stellungnahme diesbezüglich
                                    gegenüber den zuständigen Personen verpflichtet.</p>
                                <p class="text-justify">(3) Die körperliche als auch seelische Eignung kann ebenfalls jederzeit, aber vor allem bei Einstellung, durch den polizeiärztlichen Dienst geprüft und festgestellt werden.</p>
                            </div>
                            <div id="s-p-6">
                                <h6 class="text-center fw-bold  my-4" id="p-6" data-added-date="20.01.2023">§ 6<span style="display:none"> - </span><br />Alkohol- und Drogenverbot</h6>
                                <p class="text-justify">(1) Der Genuss von Alkohol oder sonstiger Genussmittel mit berauschender Wirkung vor oder
                                    während des Dienstes sind untersagt.</p>
                                <p class="text-justify">(2) Sollte die Dienstfähigkeit durch Genussmittel eingeschränkt sein, ist dies umgehend an den
                                    Vorgesetzten zu melden.</p>
                                <p class="text-justify">(3) Der Missbrauch von Medikamenten ist ebenso untersagt.</p>
                                <p class="text-justify">(4) Einnahme von Medikamenten, welche Ihre Wirkung während der Dienstzeit entfalten, ist
                                    vorher beim Dienstherrn oder dem Vorgesetzten anzumelden. Ebenso sind die Medikamente durch den polizeiärztlichen Dienst zu prüfen und freizugeben.</p>
                            </div>
                            <div id="s-p-7">
                                <h6 class="text-center fw-bold  my-4" id="p-7" data-added-date="20.01.2023">§ 7<span style="display:none"> - </span><br />Verschwiegenheit</h6>
                                <p class="text-justify">(1) Polizeivollzugsbeamte als auch Beamte im Vorbereitungsdienst (Ausbildung) sind über die
                                    ihnen oder bei Gelegenheit ihrer amtlichen Tätigkeit bekannt gewordenen dienstlichen
                                    Angelegenheiten zur Verschwiegenheit verpflichtet. Dies gilt auch über den Bereich eines
                                    Dienstherrn hinaus als auch nach Beendigung des Beamtenverhältnisses.</p>
                                <p class="text-justify">(2) Die Verschwiegenheit kann durch die Direktionsleitung, leitende Ermittler oder
                                    Pressesprecher unter genauer Evaluation gebrochen werden, wenn diese die Bekanntgabe
                                    und Veröffentlichung der Informationen für förderlich halten und es im Rahmen der
                                    rechtlichen Bestimmungen steht.</p>
                            </div>
                            <div id="s-p-8">
                                <h6 class="text-center fw-bold  my-4" id="p-8" data-added-date="26.02.2023">§ 8<span style="display:none"> - </span><br />Neutralitätsgebot</h6>
                                <p class="text-justify">(1) Jeder Polizeivollzugsbeamte muss in der Ausführung seiner Dienste, jedem Bürger –
                                    ungeachtet des Alters, der Herkunft, des sozialen Stands als auch seiner Funktion oder
                                    Position – Neutralität darbringen, um den Problemen und Bedürfnissen bestmöglich
                                    begegnen zu können.</p>
                                <p class="text-justify">(2) Bestechlichkeit ist in jedem Fall ein Ausdruck fehlender Neutralität und damit verbundener
                                    fehlender Kompetenz im Sinne der Dienstfähigkeit.</p>
                            </div>
                            <div id="s-a-4"></div>
                            <h6 class="text-center fw-bold my-5" id="a-4" data-added-date="08.01.2024">Dritter Teil<span style="display:none"> - </span><br />Dienstliches Handeln</h6>
                            <div id="s-p-9">
                                <h6 class="text-center fw-bold  my-4" id="p-9" data-added-date="20.01.2023">§ 9<span style="display:none"> - </span><br />Dienstliche Zuständigkeit; Verantwortlichkeit</h6>
                                <p class="text-justify">Die Landespolizei nimmt die ihr gegebenen Aufgaben wahr, die sowohl auf den Aufgaben
                                    des Bundesrechts als auch des Polizeirechts beruhen. Hierfür wird unterschieden zwischen:</p>
                                <p class="text-justify">(1) Ordinären Aufgaben</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Gefahrenabwehr; Kriminalprävention,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Hilfeleistung</p>
                                    </dd>
                                </dl>
                                <p class="text-justify">(2) Sekundären Aufgaben</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Strafverfolgung</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Verfolgung von Ordnungswidrigkeiten</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">3.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Verkehrsregelung und Verkehrsdienst</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">4.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Amts- und Vollzugshilfe</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">5.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Auskunftserteilung</p>
                                    </dd>
                                </dl>
                            </div>
                            <div id="s-p-10">
                                <h6 class="text-center fw-bold  my-4" id="p-10" data-added-date="20.01.2023">§ 10<span style="display:none"> - </span><br />Polizeilicher Eingriff</h6>
                                <p class="text-justify">Das polizeiliche Einschreiten ist eine hoheitliche Maßnahme, die auf dem Gewaltmonopol
                                    des Staates basiert. Es wird generell normiert durch das Polizei- und das Ordnungsrecht.</p>
                                <p class="text-justify">(1) Polizeilicher Eingriff ist in zwei Formen ausgelöst/beschrieben:</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Auf Hinweis/Aufforderung des Bürgers</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Auf Eigenverantwortung des Polizeivollzugsbeamten</p>
                                    </dd>
                                </dl>
                                <p class="text-justify">(2) Einschreitende Maßnahmen sind, beschränken sich aber nicht auf:</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Ermittlungen aller Art (bspw. strafverfolgende gemäß <a href="https://dejure.org/gesetze/StPO/163.html" class="law-link" target="_blank">§ 163 Strafprozessordnung</a>)</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Festnahmen gemäß <a href="https://dejure.org/gesetze/StPO/127.html" class="law-link" target="_blank">§ 127 Absatz 2 Strafprozessordnung</a></p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">3.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Untersuchungshaft gemäß <a href="https://dejure.org/gesetze/StPO/112.html" class="law-link" target="_blank">§ 112 Strafprozessordnung</a>, Verhöre und Vernehmungen</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">4.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Verkehrskontrollen gemäß <a href="https://dejure.org/gesetze/StVO/36.html" class="law-link" target="_blank">§ 36 Absatz 5 Straßenverkehrsordnung</a></p>
                                    </dd>
                                </dl>
                                <p class="text-justify">(3) Grundlagen dieses Einschreitens sind, beschränken sich aber nicht auf:</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Notwendigkeit der Maßnahme</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Verhältnismäßigkeit der Maßnahme zur Lagebewältigung</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">3.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Beeinträchtigungen der Personen</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">4.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Bestimmtheit, klare und erkennbare Adressierung</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">5.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Wahrung des Möglichen und des Zulässigen</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">6.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Rechtzeitige Beendigung der Maßnahme, des Einsatzes, der Lage</p>
                                    </dd>
                                </dl>
                            </div>
                            <div id="s-p-11">
                                <h6 class="text-center fw-bold  my-4" id="p-11" data-added-date="20.01.2023">§ 11<span style="display:none"> - </span><br />Ermittlungsverfahren</h6>
                                <p class="text-justify">(1) Ermittlungen sind (gemäß <a href="https://dejure.org/gesetze/StPO/163.html" class="law-link" target="_blank">§ 163 Strafprozessordnung</a>) Maßnahmen, die im Allgemeinen
                                    vonseiten der Landespolizei, spezifisch von der Kriminalpolizei ausgehen.</p>
                                <p class="text-justify">(2) Innerhalb von Ermittlungen ist in besonderer Weise die Verschwiegenheit zu wahren.</p>
                                <p class="text-justify">(3) Der Landespolizei obliegt – wie in allen Fällen – die Beweislast. Beweise müssen durch
                                    den Ankläger, also die Polizei, erbracht werden.</p>
                            </div>
                            <div id="s-p-12">
                                <h6 class="text-center fw-bold  my-4" id="p-12" data-added-date="20.01.2023">§ 12<span style="display:none"> - </span><br />Berichte; Dokumentation</h6>
                                <p class="text-justify">(1) Die möglichst ausführliche Dokumentation von Einsätzen und Maßnahmen ist für jeden
                                    Polizeivollzugsbeamten verpflichtend, sobald er die Einsatzleitung übernimmt, eine Person
                                    verstirbt oder zu Schaden kam.</p>
                                <p class="text-justify">(2) Weiterhin muss ein Einsatzbericht erstellt werden, wenn ein Ermittlungsverfahren in der
                                    Sache absehbar ist, oder eine der beteiligten Personen/Parteien dies wünscht.</p>
                                <p class="text-justify">(3) Die jeweiligen Formvorgaben sind den Formatvorgaben zu entnehmen.</p>
                            </div>
                            <div id="s-p-13">
                                <h6 class="text-center fw-bold  my-4" id="p-13" data-added-date="20.01.2023">§ 13<span style="display:none"> - </span><br />Strafanträge-/anzeigen</h6>
                                <p class="text-justify">(1) Bei der Aufnahme von Anzeigen ist eine genaue Beschreibung und Dokumentation
                                    essenziell.</p>
                                <p class="text-justify">(2) Die Bearbeitung von Anzeigen erfolgt in der Regel nur auf einem Weg. Hierfür erfolgt die
                                    Bearbeitung durch die Kriminalpolizei/den Kriminaldauerdienst, sollten eben jene Beamte
                                    nicht verfügbar sein und hat der Fall eine Präzedenz, so wird die Anzeige durch Beamte
                                    des mittleren und gehobenen Polizeivollzugsdienstes bearbeitet.</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Eine möglichst genaue und detailreiche Beschreibung der Maßnahmen ist hierbei
                                            dringend erforderlich.</p>
                                    </dd>
                                </dl>
                            </div>
                            <div id="s-p-14">
                                <h6 class="text-center fw-bold  my-4" id="p-14" data-added-date="20.01.2023">§ 14<span style="display:none"> - </span><br />Verwertung privaten Wissens</h6>
                                <p class="text-justify">(1) Erlangt ein Polizeivollzugsbeamter Kenntnis über ein Verbrechen oder ist er im Wissen
                                    über ein bevorstehendes Verbrechen – dieses Wissens aus einer privaten Quelle –
                                    entspringend, so ist er, im Rahmen des Strafgesetzbuches, verpflichtet, diese Tat, eventuell
                                    behördenübergreifend, zu melden.</p>
                                <p class="text-justify">(2) Hat ein Polizeivollzugsbeamter Hinweise oder Kenntnis über Verbrecher oder Gruppen, die
                                    der Erarbeitung oder Bekämpfung dieser Person dienen, so ist er verpflichtet, diese
                                    Hinweise an entsprechende Beamte, Sachbearbeiter und Weitere zu melden.</p>
                                <p class="text-justify">(3) Steht der Polizeivollzugsbeamte in Sachen nach Absatz 2 im direkten Kontakt mit Opfer, Täter,
                                    dem Tatverdächtigen oder Zeugen, so ist er zur Wahrung der Neutralität in besonderem
                                    Maße verpflichtet. Ebenfalls ist die Federführung an einen qualifizierten Kollegen
                                    abzugeben, darf an dem Fall aber kontinuierlich teilhaben.</p>
                            </div>
                            <div id="s-p-15">
                                <h6 class="text-center fw-bold  my-4" id="p-15" data-added-date="20.01.2023">§ 15<span style="display:none"> - </span><br />Dienstantritt und -ablösung; Krankheit; Urlaub</h6>
                                <p class="text-justify">(1) Der Dienstantritt ist stets per Funk (über die Zuteilung) oder persönlich bei der Leitstelle
                                    bekannt zu geben.</p>
                                <p class="text-justify">(2) Weiterhin ist darauf zu achten, dass der Beamte zu Dienstantritt seine entsprechende
                                    Uniform oder angepasste (im Einsatzdienst auch nur die dafür designierte) Dienstkleidung trägt, seine Einsatzmittel allesamt einsatzbereit
                                    und bei sich hat und den ersten Weisungen der Leitstelle folgt.</p>
                                <p class="text-justify">(3) Verlässt ein Beamter den Dienst, so hat er dies ebenfalls zwingend bei der Leitstelle oder
                                    dem Vorgesetzten anzumelden. Wenn möglich, sollte der Kollege durch einen anderen
                                    abgelöst werden.</p>
                                <p class="text-justify">(4) Ein konkreter Schichtdienst ist nicht möglich. Ablösung im Sinne dieser Vorschrift bedeutet
                                    im weiteren Sinn auch das Ausscheiden aus dem Dienst aufgrund medizinischer Probleme.</p>
                                <p class="text-justify">(5) Sollte ein Beamter im Einsatz verwundet werden oder ist krank, so ist dies dem
                                    Vorgesetzten zu melden.</p>
                                <p class="text-justify">(6) Urlaub gilt ab drei Tagen, ab dem dritten Tag muss Urlaub schriftlich beim Vorgesetzten
                                    oder Dienstherren anzumelden. Vorher ist keine Anmeldung nötig.</p>
                                <p class="text-justify">(7) Zu Dienstbesprechungen und durch den Dienstherren oder den Vorgesetzten kommunizierte Pflichtterminen ist in jedem Fall eine Abmeldung vonnöten.</p>
                            </div>
                            <div id="s-p-16">
                                <h6 class="text-center fw-bold  my-4" id="p-16" data-added-date="20.01.2023">§ 16<span style="display:none"> - </span><br />Diensteigentum</h6>
                                <p class="text-justify">(1) Ausgeteilte und zugewiesene Dienstgegenstände und Einsatzmittel der Landespolizei sind
                                    Eigentum des Staates.</p>
                                <p class="text-justify">(2) Die mutwillige Beschädigung oder der mutwillige Verkauf von Dienstgegenständen wird
                                    strafrechtliche geahndet.</p>
                                <p class="text-justify">(3) Unter Dienstgegenständen sind folgende Dinge zu verstehen:</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Einsatz- und Führungsmittel (Funkgeräte, Dienstwaffen und Munition,
                                            Schutzausrüstung/-kleidung, Absperrmaterial, Handfesseln usw.),</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Einsatz- und Dienstfahrzeuge,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">3.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Uniformen und sonstige Dienstkleidung.</p>
                                    </dd>
                                </dl>
                                <p class="text-justify">(4) Der angemessene, aufmerksame und achtsame Umgang mit Dienstgegenständen ist
                                    grundlegend verpflichtend. Die Pflege von Dienstgegenständen ist ebenso Pflicht.
                                    Reparaturen werden durch den Dienstherrn getragen.</p>
                                <p class="text-justify">(5) Die Verwendung von Dienstgegenständen für private Zwecke oder außerhalb des Dienstes ist durch den Dienstherren ausdrücklich untersagt. Zuwiderhandlung wird nach <a href="https://dejure.org/gesetze/StGB/242.html" class="law-link" target="_blank">§ 242 Strafgesetzbuch</a> geahndet.</p>
                            </div>
                            <div id="s-p-17">
                                <h6 class="text-center fw-bold  my-4" id="p-17" data-added-date="20.01.2023">§ 17<span style="display:none"> - </span><br />Umgang mit Dienstwaffen</h6>
                                <p class="text-justify">Die Regulierungen im Umgang mit der Dienstwaffe sind wie folgt:</p>
                                <p class="text-justify">(1) Gegen eine einzelne Person</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Verhinderung einer Straftat.</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Verhinderung der Entziehung eines Straftäters aus der Verhaftung/Festnahme.</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">3.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Vereitelung der Flucht oder zur Wiederergreifung eines Straftäters.</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">4.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Verhinderung einer Flucht(-ermöglichung) durch Dritte.</p>
                                    </dd>
                                </dl>
                                <p class="text-justify">(2) Tödlicher Schuss</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Einziges Mittel zur Abwehr gegenwärtiger Lebensgefahr oder gegenwärtiger Gefahr
                                            einer schwerwiegenden Verletzung der körperlichen Unversehrtheit.</p>
                                    </dd>
                                </dl>
                                <p class="text-justify">(3) Gegen Menschenmengen</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Verhinderung von Gewalttaten oder Straftaten.</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Fehlerfolg von einzelnen Zwangsmaßnahmen.</p>
                                    </dd>
                                </dl>
                                <p class="text-justify">(4) Diese Regularien sind unveränderlich.</p>
                            </div>
                            <div id="s-p-18">
                                <h6 class="text-center fw-bold  my-4" id="p-18" data-added-date="20.01.2023">§ 18<span style="display:none"> - </span><br />Unmittelbarer Zwang</h6>
                                <p class="text-justify">(1) Der unmittelbare Zwang ist nur einzusetzen, wenn kein anderes Mittel und keine Maßnahme
                                    Erfolg zeigt. Ebenso muss die eingesetzte Mittel angemessen in seiner Härte und
                                    Durchführung durchdacht sein.</p>
                                <p class="text-justify">(2) Die Anwendung von unmittelbarem Zwang muss angekündigt werden.</p>
                                <p class="text-justify">(3) Die Dienstwaffe eines Polizeivollzugsbeamten muss stets beschützt und gepflegt sein.</p>
                                <p class="text-justify">(4) Der Einsatz von Gewalt im Rahmen von unmittelbarem Zwang ist wie folgt reguliert:</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Jeder Polizeivollzugsbeamte unternimmt alles, um eine Konfrontation möglichst
                                            gewaltfrei zu beenden. Zwangs- und Gewaltanwendung sollten nur zur Anwendung
                                            kommen, wenn dies die Einsatzregeln vorsehen und gewaltlose Mittel nicht zum Ziel
                                            führen.</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Ist die Anwendung von Zwang oder Gewalt zur Erfüllung der Aufgaben vorgesehen,
                                            darf diese in keinem Fall über das absolut notwendige Maß hinausgehen.</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">3.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Ist es abzusehen, dass eine vorgesehene oder angesetzte Zwangs-
                                            /Gewaltanwendung zu einer Gefährdung oder Schädigung Dritter führen könnte, die
                                            in keinem Verhältnis zum erwarteten Erfolg steht, muss ein anderes Vorgehen
                                            gewählt werden.</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">4.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Nach jeder Eskalation der Gewalt müssen zwingend Maßnahmen ins Auge gefasst
                                            werden, welche primär zur Deeskalation und Stabilisierung der Situation beitragen.</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">5.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Jeder Polizeivollzugsbeamte ist für die Anwendung von unmittelbarem Zwang oder
                                            Gewalt direkt und persönlich verantwortlich. Er muss selbst erkennen, wann und
                                            unter welchen Umständen die Anwendung verhältnismäßig und notwendig ist. Weiter
                                            stellt er die Anwendung ein, sobald dies die Auftragserfüllung zulässt.</p>
                                    </dd>
                                </dl>
                            </div>
                            <div id="s-p-19">
                                <h6 class="text-center fw-bold  my-4" id="p-19" data-added-date="20.01.2023">§ 19<span style="display:none"> - </span><br />Einsatzfahrzeuge</h6>
                                <p class="text-justify">(1) Dienst- und Einsatzfahrzeuge müssen stets entsprechend der Straßenverkehrs-Ordnung,
                                    Straßenverkehrs-Zulassungsordnung und des Straßenverkehrsgesetzes geführt werden. Dies ist vor Benutzung des Dienstfahrzeugs durch den Fahrzeugführer zu prüfen.</p>
                                <p class="text-justify">(2) Regelungen bezüglich Sonder- und Wegerechte (gemäß <a href="https://dejure.org/gesetze/StVO/35.html" class="law-link" target="_blank">§ 35 Straßenverkehrs-Ordnung</a>) gelten entsprechend.</p>
                                <p class="text-justify">(3) Fahrzeuge sind möglichst nur fahrtüchtig (bestenfalls unversehrt) und mit einer Tankfüllung
                                    von mindestens 50 % in die Garage einzuparken.</p>
                                <p class="text-justify">(4) Bei erwartbaren längeren Aufenthalten innerhalb einer Dienststelle oder auf dem Gelände
                                    einer Dienststelle sind Fahrzeuge möglichst in die Garage einzuparken.</p>
                                <p class="text-justify">(5) Vor Fahrtantritt hat der Fahrzeugführer sowohl das Handschuhfach als auch den Kofferraum auf den fach- und ordnungsgemäßen Inhalt zu überprüfen. Ebenso ist auf die mangelnde Einlagerung von sichergestellten Gegenständen zu achten. Abweichungen und Diskrepanzen sind umgehend dem Dienstherren zu melden.</p>
                                <p class="text-justify">(6) Es dürfen nur Fahrzeuge der entsprechenden Abteilung (Dezernat oder Team) und Qualifikation besetzt werden.</p>
                                <p class="text-justify">(7) Die Verwendung jeglicher ziviler (oder privater) Fahrzeuge bedingt die außerordentliche Genehmigung durch den Dienstherren.</p>
                            </div>
                            <div id="s-p-20">
                                <h6 class="text-center fw-bold  my-4" id="p-20" data-added-date="20.01.2023">§ 20<span style="display:none"> - </span><br />Einsatzleitung</h6>
                                <p class="text-justify">(1) Eine Einsatzleitung ist selbstständig und verpflichtend zu bestimmen.
                                    Grundsätzlich übernimmt der ranghöchste Beamte oder ein Beamter des Einsatzleitdienstes.
                                </p>
                                <p class="text-justify">(2) Der Einsatzleiter ist vor Ort für die Koordination und Einweisung von Einsatzkräften
                                    zuständig. Dabei werden die Anordnungen und Befehle nur durch ihn oder
                                    Führungspersonen erteilt. Das Entfernen von der Einsatzstelle ist nur in Absprache mit dem Einsatzleiter gestattet.</p>
                                <p class="text-justify">(3) Eine Einsatzleitung muss gestellt werden, wenn</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Ein Großereignis (Geiselnahme, Bankraub etc.) vorliegt,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Ein Schusswechsel (mit Personenschaden) stattfindet oder stattgefunden hat,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">3.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Mehr als vier Streifenwagen oder mehr als acht Beamte an einer Einsatzlage beteiligt sind,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">4.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Es sich um eine Razzia oder sonstige geplante Einsatzlage handelt, oder</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">5.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Das Führungs- und Lagezentrum (FLZ) beziehungsweise die Leitstelle der Polizei einen solchen anfordert.</p>
                                    </dd>
                                </dl>
                            </div>
                            <div id="s-p-21">
                                <h6 class="text-center fw-bold  my-4" id="p-21" data-added-date="20.01.2023">§ 21<span style="display:none"> - </span><br />Aus-, Fort- und Weiterbildung</h6>
                                <p class="text-justify">(1) Kontinuierliche persönliche Weiterentwicklung ist im Zuge des dienstlichen Verständnisses
                                    Grundvoraussetzung. Jeder Polizeivollzugsbeamte ist dazu angehalten, sich stets
                                    weiterzubilden und sein Wissen im Dienst zu erweitern und zu erproben.</p>
                                <p class="text-justify">(2) Der Dienstherr ist dazu verpflichtet, Zeit und Möglichkeit zur persönlichen
                                    Weiterentwicklung anzubieten.</p>
                            </div>
                            <div id="s-p-22">
                                <h6 class="text-center fw-bold  my-4" id="p-22" data-added-date="20.01.2023">§ 22<span style="display:none"> - </span><br />Vorgesetzte</h6>
                                <p class="text-justify">(1) Vorgesetzte eines Polizeivollzugsbeamten sind zu jeder Zeit:</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Der Inspekteur der Landespolizei - und seine ständigen Vertreter,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Der höhere Dienst (Laufbahngruppe 2.1),</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">3.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify"> Der ranghöchste Beamte im Dienst (Schichtleiter),</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">4.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">In der Tätigkeit als Leitstelle – Disponenten,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">5.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Einsatzleiter.</p>
                                    </dd>
                                </dl>
                                <p class="text-justify">(2) Vorgesetzte eines Polizeivollzugsbeamten sind abhängig der Situation und des Sachverhalts:</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Die zuständige Dezernatsleitung,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Die zuständige Teamleitung,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">3.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Kollegen der Dienst- und Fachaufsicht,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">4.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Praxisanleiter und Personaler,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">5.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Kollegen mit einem höheren Dienstgrad.</p>
                                    </dd>
                                </dl>
                            </div>
                            <div id="s-p-23">
                                <h6 class="text-center fw-bold  my-4" id="p-23" data-added-date="20.01.2023">§ 23<span style="display:none"> - </span><br />Rechtsbeistand</h6>
                                <p class="text-justify">(1) Sollten Tatverdächtige, Täter oder Beschuldigte anwaltliche Vertretung wünschen, so ist
                                    dies durch Polizeivollzugsbeamte in vollem Maße wahrzunehmen und möglichst ein
                                    geprüfter Rechtsanwalt zu organisieren.</p>
                                <p class="text-justify">(2) Vor Beginn des Mandats ist die ausgestellte Anwaltslizenz zu erfragen und prüfen – diese
                                    muss dauerhaft mit sich geführt werden.</p>
                                <p class="text-justify">(3) Nur nach dem erfolglosen Versuch, einen Rechtsbeistand zu erreichen, darf einem
                                    Tatverdächtigen, Täter oder Beschuldigten dieser zur einzelnen Fallklärung verweigert
                                    werden.</p>
                                <p class="text-justify">(4) Vor einer verwertbaren Befragung sind Tatverdächtige und Zeugen zu belehren. Sollte dies nicht geschehen, kann die Aussage als nichtig erklärt werden.</p>
                            </div>
                            <div id="s-p-24">
                                <h6 class="text-center fw-bold  my-4" id="p-24" data-added-date="20.01.2023">§ 24<span style="display:none"> - </span><br />Haft und Hafteinheiten</h6>
                                <p class="text-justify">(1) Die maximale Anzahl an Hafteinheiten, die einer Person auferlegt werden können, liegt bei
                                    120.</p>
                                <p class="text-justify">(2) Sollte die maximale Anzahl an Hafteinheiten durch die begangenen Delikte überschritten
                                    werden, so sind weitere Strafen entweder zu erlassen oder von Hafteinheiten in Bußgeld
                                    umzurechnen.</p>
                                <p class="text-justify">(3) Die gestellten Strafanträge sind von dieser Limitierung nicht betroffen, rein das Strafmaß
                                    wird limitiert.
                                </p>
                            </div>
