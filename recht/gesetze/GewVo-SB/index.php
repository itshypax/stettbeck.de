                            <div id="s-p-1">
                                <h6 class="text-center fw-bold my-4" id="p-1" data-added-date="12.07.2023">§ 1<span style="display:none"> - </span><br>Begriffsdefinition</h6>
                                <p class="text-justify">(1) Als „Gehaltszeitraum“ im Sinne dieser Verordnung gilt der Zeitraum, in dem durch die Vorgabe der Kommune ein festes Gehalt für die geleisteten Tätigkeiten ausbezahlt wird.</p>
                                <p class="text-justify">(2) Als „geschäftsführende Person“ wird grundsätzlich der Inhaber bezeichnet. In Abhängigkeit zum Tätigkeitsfeld kann diese Definition um jede Person mit führenden Tätigkeiten innerhalb des Unternehmens erweitert werden.</p>
                                <p class="text-justify">(3) Als „Arbeitsverhältnis“ im Sinne dieser Verordnung gilt sowohl das Arbeitsverhältnis zwischen Arbeitgeber und Arbeitnehmer als auch das Ausbildungsverhältnis zwischen Arbeitgeber und Auszubildenden.</p>
                            </div>
                            <div id="s-p-2">
                                <h6 class="text-center fw-bold my-4" id="p-2" data-added-date="12.07.2023">§ 2<span style="display:none"> - </span><br>Erfordernis eines Gewerbes</h6>
                                <p class="text-justify">(1) Wer sich zusammenschließt, um im kaufmännischen Sinne die Erreichung eines gemeinsamen Zweckes zu fördern, insbesondere durch finanzielle Mittel, hat ein ordentliches Unternehmen zu begründen.</p>
                                <p class="text-justify">(2) Unternehmen, Eigenbetriebe oder Kommunalanstalten des Landes oder der Kommune können in Einzelbestimmung von Teilen dieser Rechtsverordnung entbunden sein.</p>
                            </div>
                            <div id="s-p-3">
                                <h6 class="text-center fw-bold my-4" id="p-3" data-added-date="12.07.2023">§ 3<span style="display:none"> - </span><br>Information über Gewerbeaufnahme</h6>
                                <p class="text-justfiy">(1) Zur Aufnahme eines Gewerbes müssen folgende Daten an die zuständige Aufsichtsbehörde übermittelt werden:</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Name des Unternehmens,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Rechtsform des Unternehmens,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">3.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Branchenzuordnung,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">4.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Name, Geburtsdatum und Geburtsort der geschäftsführenden juristischen Person, und</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">5.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">eine unterschriebene Kopie des Gesellschaftervertrags.</p>
                                    </dd>
                                </dl>
                                <p class="text-justfiy">(2) Die Übermittlung des Gesellschaftervertrags ist optional und nur bei einem vorhandenen Vertrag notwendig.</p>
                                <p class="text-justfiy">(3) Nach der Information über eine Gewerbeaufnahme besteht kein Anspruch auf staatliche Förderung oder eine Eintragung ins Gewerberegister.</p>
                            </div>
                            <div id="s-p-4">
                                <h6 class="text-center fw-bold my-4" id="p-4" data-added-date="12.07.2023">§ 4<span style="display:none"> - </span><br>Gewerbegründung; Beantragung eines Gewerbes</h6>
                                <p class="text-justify">(1) Um ein Gewerbe zu gründen, muss dieses bei der zuständigen Behörde beantragt und von dieser genehmigt werden.</p>
                                <p class="text-justify">(2) Zusätzlich zu den Daten gemäß § 3 Abs. 1 sind zusätzlich folgende Daten zu übermitteln:</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Relevante Qualifikationen der geschäftsführenden juristischen Person,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Tätigkeitsbeschreibung, und</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">3.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Auflistung der für die Gründung erforderlichen oder gewünschten Mittel.</p>
                                    </dd>
                                </dl>
                                <p class="text-justify">(3) Die Auflistung der Mittel nach Abs. 2 Nr. 3 ist optional, insofern vorhanden ist hierfür die gegebene Vorlage der Aufsichtsbehörde zu nutzen.</p>
                                <p class="text-justify">(4) Die Aufsichtsbehörde kann den Antrag aus rechtfertigenden Gründen ablehnen. Die Begründung ist in jedem Fall mitzuteilen.</p>
                                <p class="text-justify">(5) Nach Gründung eines Gewerbes kann Anspruch auf staatliche Förderung oder eine Eintragung ins Gewerberegister bestehen.</p>
                            </div>
                            <div id="s-p-5">
                                <h6 class="text-center fw-bold my-4" id="p-5" data-added-date="12.07.2023">§ 5<span style="display:none"> - </span><br>Gesellschaftervertrag</h6>
                                <p class="text-justify">(1) Ein Gesellschaftervertrag ist einstimmig durch alle geschäftsführenden Personen zu genehmigen und als Kopie der Aufsichtsbehörde zukommen zu lassen, um in Kraft zu treten.</p>
                                <p class="text-justify">(2) In einem Gesellschaftervertrag können die Haftung, der Gewinn und die Beauftragungen für alle geschäftsführenden Personen festgelegt werden.</p>
                                <p class="text-justify">(3) Die Haftung ist, wenn gesetzliche Vorschriften eine juristische Person in der verwendeten Rechtsform benennen, auf mindestens eine juristische Person festzulegen. Alle Haftenden müssen den Vertrag vor Inkrafttreten genehmigen.</p>
                                <p class="text-justify">(4) Ein Gesellschaftervertrag ist grundsätzlich formlos und in eigener Form zu erstellen. Lediglich die Unterschriften aller geschäftsführenden Personen müssen zwingend vorhanden sein und den Personen zuordenbar gestaltet werden.</p>
                            </div>
                            <div id="s-p-6">
                                <h6 class="text-center fw-bold my-4" id="p-6" data-added-date="12.07.2023">§ 6<span style="display:none"> - </span><br>Gewerbestrafen</h6>
                                <p class="text-justify">(1) Bei groben, fahrlässigen, gefährlichen, vermehrten oder sonstigen Verstößen ist die Aufsichtsbehörde dazu befähigt Gewerbe entweder vorübergehend oder bis auf Widerruf zu schließen oder den Betrieb zu untersagen. Hierfür muss eine schriftliche Stellungnahme beinhaltend der Begründung zur Maßnahmenerhebung an eine geschäftsführende Person versendet und eröffnet werden.</p>
                                <p class="text-justify">(2) In besonderen Fällen ist die Aufsichtsbehörde ebenfalls dazu befugt einen Gewerbebetrieb in Gänze zu untersagen, ein Berufsausübungsverbot auszusprechen oder erlangte Berufsausbildungen, Titel oder sonstige beruflichen Zertifikate abzuerkennen.</p>
                                <p class="text-justify">(3) Für Maßnahmen gemäß Abs. 2 ist ebenfalls eine Kundgabe entsprechend Abs. 1 S. 2 von Nöten.</p>
                                <p class="text-justify">(4) Zusätzlich zu den benannten Maßnahmen kann die Aufsichtsbehörde Ordnungsgelder gegen Unternehmen erheben. Diese sind ebenfalls gemäß Abs. 1 S. 2 kundzugeben. Zusätzlich ist ein Bescheid über das Ordnungsgeld anzufügen.</p>
                            </div>
                            <div id="s-p-7">
                                <h6 class="text-center fw-bold my-4" id="p-7" data-added-date="12.07.2023">§ 7<span style="display:none"> - </span><br>Buchhaltung; Werkverträge</h6>
                                <p class="text-justfiy">(1) Gegründete Gewerbe nach § 4 haben über Ein- und Ausnahmen nachvollziehbar Protokoll zu führen.</p>
                                <p class="text-justfiy">(2) Die Aufsichtsbehörde kann Unternehmen zu jederzeit, unter begründetem Verdacht, dazu auffordern ihre Buchhaltung offen zu legen.</p>
                                <p class="text-justfiy">(3) Wer Vorteile durch Werkverträge erhält, welche durch das Land oder die Kommune subventioniert oder vermittelt werden, hat seinen Gewinn am Verkauf auf 40 Prozent zu begrenzen.</p>
                            </div>
                            <div id="s-p-8">
                                <h6 class="text-center fw-bold my-4" id="p-8" data-added-date="12.07.2023">§ 8<span style="display:none"> - </span><br>Mindestlohn</h6>
                                <p class="text-justify">(1) Jedem in einem Vollzeitarbeitsverhältnis angestellten Mitarbeiter steht der gesetzlich festgelegte Mindestlohn zu.</p>
                                <p class="text-justify">(2) Mitarbeiter in einem Teilzeitarbeitsverhältnis steht in jedem Fall 50 Prozent des gesetzlich festgelegten Mindestlohns zu.</p>
                                <p class="text-justify">(3) Auszubildenden steht in jedem Fall 30 Prozent des gesetzlich festgelegten Mindestlohns zu.</p>
                                <p class="text-justify">(4) Der Mindestlohn ist für jeden Gehaltszeitraum, insofern im Arbeitsvertrag nicht anders geregelt, auszuzahlen.</p>
                                <p class="text-justify">(5) Zum 24. Juli 2023 wird die Höhe des Mindestlohns auf 1.600,00 EUR festgelegt.</p>
                                <p class="text-justify">(6) Kleingewerbe können in Einzelfällen durch die Aufsichtsbehörde von der Zahlung des Mindestlohns entbunden werden.</p>
                            </div>
                            <div id="s-p-9">
                                <h6 class="text-center fw-bold my-4" id="p-9" data-added-date="12.07.2023">§ 9<span style="display:none"> - </span><br>Anstellung und Beendigung</h6>
                                <p class="text-justify">(1) Zur Begründung eines Arbeitsverhältnisses ist eine schriftliche Vertragsregelung, namentlich ein „Arbeitsvertrag“, zwischen Arbeitgeber und Arbeitnehmer abzuschließen. Die Anstellung ist beidseitig zu bewilligen. Die Arbeit beginnt, solange nicht anders im Arbeitsvertrag bestimmt, unmittelbar mit Vertragsschluss.</p>
                                <p class="text-justify">(2) Zur außervertragsmäßigen Aufhebung des Arbeitsverhältnisses ist eine schriftliche Vertragsregelung, namentlich ein „Aufhebungsvertrag“, zwischen Arbeitgeber und Arbeitnehmer abzuschließen. Die Aufhebung ist beidseitig zu bewilligen.</p>
                                <p class="text-justify">(3) Zur außervertragsmäßigen Kündigung eines Arbeitsverhältnisses durch Arbeitgeber oder Arbeitnehmer bedarf es der Schriftform. Die Kündigung erfolgt einseitig.</p>
                                <p class="text-justify">(4) Die vertragsmäßige Beendigung des Arbeitsverhältnisses ist durch eine Befristung im Arbeitsvertrag zu regeln. Ist keine eindeutige Befristung bestimmt, so ist das Verhältnis unbefristet. Eine Befristung über mehr als vier Wochen ist unzulässig.</p>
                            </div>
                            <div id="s-p-10">
                                <h6 class="text-center fw-bold my-4" id="p-10" data-added-date="12.07.2023">§ 10<span style="display:none"> - </span><br>Kündigung</h6>
                                <p class="text-justify">(1) Eine Kündigung während der Probezeit ist sowohl durch Arbeitnehmer als auch Arbeitgeber jederzeit fristlos, ohne Nennung von Gründen, möglich.</p>
                                <p class="text-justify">(2) Eine Kündigung des Arbeitnehmers ist, unter der Nennung von Gründen, nach Ablauf der Probezeit nur dann fristlos möglich, wenn keine Kündigungsfrist im Arbeitsvertrag vereinbart wurde. Eine vereinbarte Kündigungsfrist von mehr als zwei Wochen ist ungültig.</p>
                                <p class="text-justify">(3) Kündigungen des Arbeitgebers haben eine Frist von 14 Tagen, solange nichts anderes im Arbeitsvertrag geregelt ist. Die Kündigungsfrist des Arbeitgebers kann vertraglich auf einen Zeitraum zwischen sieben und 28 Tage bestimmt werden.</p>
                                <p class="text-justify">(4) Die Kündigung seitens Arbeitgeber ist jederzeit und fristlos möglich, wenn <a href="https://dejure.org/gesetze/BGB/626.html" class="law-link" target="_blank">§ 626 Bürgerliches Gesetzbuch (BGB)</a> begründet ist.</p>
                                <p class="text-justify">(5) Eine Kündigung durch den Arbeitgeber ist nur erlaubt, wenn der Arbeitnehmer bereits dreimal oder bei wiederholtem Auftreten desselben oder ähnlichen Fehlers abgemahnt wurde. Eine Kündigung durch den Arbeitgeber kann auch ohne vorherige Abmahnung erfolgen, wenn</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Der Arbeitnehmer die Arbeit mehrere Tage anhaltend verweigert,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Der Arbeitnehmer während der Arbeitszeit schwere Straftaten begeht,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">3.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Der Arbeitnehmer außerhalb der Arbeitszeit schwere Straftaten begeht, die in seinem Tätigkeitsfeld Einschränkungen verursachen, oder</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">4.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">betriebsbedingte Gründe vorliegen, wie</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em;margin-left:2.5em;">a)</dt>
                                    <dd style="margin-left: 5em; margin-bottom: 3ex">
                                        <p class="text-justify">die Stilllegung des Betriebs,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em;margin-left:2.5em;">b)</dt>
                                    <dd style="margin-left: 5em; margin-bottom: 3ex">
                                        <p class="text-justify">die Einstellung der Produktion, oder</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em;margin-left:2.5em;">c)</dt>
                                    <dd style="margin-left: 5em; margin-bottom: 3ex">
                                        <p class="text-justify">das Fehlen besonders wichtiger Materialien für die Tätigkeit oder Alternativtätigkeit.</p>
                                    </dd>
                                </dl>
                            </div>
                            <div id="s-p-11">
                                <h6 class="text-center fw-bold my-4" id="p-11" data-added-date="12.07.2023">§ 11<span style="display:none"> - </span><br>Mahnung</h6>
                                <p class="text-justify">(1) Der Arbeitgeber kann seinen angestellten Arbeitnehmer abmahnen. Die Abmahnung erfordert der Schriftform.</p>
                                <p class="text-justify">(2) Für dasselbe kann nicht mehrfach abgemahnt werden. In Tateinheit kann nicht mehrfach abgemahnt werden.</p>
                                <p class="text-justify">(3) Gründe einer Abmahnung sind personenbedingt, verhaltensbedingt oder betriebsbedingt. Gründe in diesem Sinne sind insbesondere</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Zur Person bedingt, wenn</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em;margin-left:2.5em;">a)</dt>
                                    <dd style="margin-left: 5em; margin-bottom: 3ex">
                                        <p class="text-justify">der Arbeitnehmer unerlaubt dem Geschäft nachgeht,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em;margin-left:2.5em;">b)</dt>
                                    <dd style="margin-left: 5em; margin-bottom: 3ex">
                                        <p class="text-justify">der Arbeitnehmer nicht kompetent genug für die minimale Arbeitsleistung ist,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em;margin-left:2.5em;">c)</dt>
                                    <dd style="margin-left: 5em; margin-bottom: 3ex">
                                        <p class="text-justify">der Arbeitnehmer eine fehlende politische oder religiöse Zuverlässigkeit vorweist, oder</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em;margin-left:2.5em;">d)</dt>
                                    <dd style="margin-left: 5em; margin-bottom: 3ex">
                                        <p class="text-justify">der Arbeitnehmer unter untragbarer Trink- oder Drogensucht leidet.</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Zum Verhalten bedingt, wenn</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em;margin-left:2.5em;">a)</dt>
                                    <dd style="margin-left: 5em; margin-bottom: 3ex">
                                        <p class="text-justify">der Arbeitnehmer die Arbeit verweigert,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em;margin-left:2.5em;">b)</dt>
                                    <dd style="margin-left: 5em; margin-bottom: 3ex">
                                        <p class="text-justify">dem Arbeitnehmer der Leistungswille fehlt,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em;margin-left:2.5em;">c)</dt>
                                    <dd style="margin-left: 5em; margin-bottom: 3ex">
                                        <p class="text-justify">der Arbeitnehmer vertragliche Nebenpflichten verletzt,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em;margin-left:2.5em;">d)</dt>
                                    <dd style="margin-left: 5em; margin-bottom: 3ex">
                                        <p class="text-justify">der Arbeitnehmer ein Alkohol- oder Rauchverbot im Betrieb missachtet,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em;margin-left:2.5em;">e)</dt>
                                    <dd style="margin-left: 5em; margin-bottom: 3ex">
                                        <p class="text-justify">der Arbeitnehmer Personen während der Arbeitszeit verbal attackiert – sie beleidigt,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em;margin-left:2.5em;">f)</dt>
                                    <dd style="margin-left: 5em; margin-bottom: 3ex">
                                        <p class="text-justify">der Arbeitnehmer unpünktlich ist,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em;margin-left:2.5em;">g)</dt>
                                    <dd style="margin-left: 5em; margin-bottom: 3ex">
                                        <p class="text-justify">der Arbeitnehmer unbefugt den Arbeitsplatz verlässt,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em;margin-left:2.5em;">h)</dt>
                                    <dd style="margin-left: 5em; margin-bottom: 3ex">
                                        <p class="text-justify">der Arbeitnehmer eine zumutbare Therapie bei Krankheit ablehnt, solange diese verhältnismäßig und tragbar ist, oder</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em;margin-left:2.5em;">i)</dt>
                                    <dd style="margin-left: 5em; margin-bottom: 3ex">
                                        <p class="text-justify">der Arbeitnehmer regelhaft unzureichend anwesend ist.</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">3.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Zum Betrieb bedingt, wenn</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em;margin-left:2.5em;">a)</dt>
                                    <dd style="margin-left: 5em; margin-bottom: 3ex">
                                        <p class="text-justify">der Betrieb stillegelegt wird,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em;margin-left:2.5em;">b)</dt>
                                    <dd style="margin-left: 5em; margin-bottom: 3ex">
                                        <p class="text-justify">eine Produktion eingestellt wird,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em;margin-left:2.5em;">c)</dt>
                                    <dd style="margin-left: 5em; margin-bottom: 3ex">
                                        <p class="text-justify">ein besonderer Rohstoffmangel herrscht.</p>
                                    </dd>
                                </dl>
                            </div>
                            <div id="s-p-12">
                                <h6 class="text-center fw-bold my-4" id="p-12" data-added-date="12.07.2023">§ 12<span style="display:none"> - </span><br>Probezeit</h6>
                                <p class="text-justify">(1) Während der Probezeit kann das Arbeitsverhältnis gemäß § 10 Abs. 1 jederzeit, fristlos und ohne Grund beendet werden.</p>
                                <p class="text-justify">(2) Die Probezeit beginnt mit dem Beginn des Arbeitsverhältnisses. Sie endet frühestens nach einer, spätestens nach vier Wochen. Sollte die Probezeit nicht vertraglich geregelt sein, so dauert die Probezeit eine Woche.</p>
                            </div>
                            <div id="s-p-13">
                                <h6 class="text-center fw-bold my-4" id="p-13" data-added-date="12.07.2023">§ 13<span style="display:none"> - </span><br>Vergütung</h6>
                                <p class="text-justify">(1) Die Vergütung ist ohne Abzüge direkt an den Arbeitnehmer oder an ein Konto des Arbeitnehmers auszuzahlen. Insofern nicht automatisiert hat dies spätestens alle 30 Tage zu erfolgen.</p>
                                <p class="text-justify">(2) Arbeitnehmer sind für den zeitlichen Aufwand ihrer Geschäftstätigkeit zu entgelten. Eine rein leistungsbezogene Vergütung ist untersagt, sie kann jedoch zusätzlich erfolgen.</p>
                                <p class="text-justify">(3) Es können durch den Arbeitgeber Zusatzvergütungen, insbesondere auf Leistungen bezogen, erfolgen. Diese sind vertraglich zu bestimmen.</p>
                            </div>
                            <div id="s-p-14">
                                <h6 class="text-center fw-bold my-4" id="p-14" data-added-date="12.07.2023">§ 14<span style="display:none"> - </span><br>Folgepflicht des Arbeitnehmers</h6>
                                <p class="text-justify">(1) Der Arbeitgeber kann dem Arbeitnehmer Weisungen erteilen, welchen zu folgen ist. Es können auch generelle Vorschriften erlassen werden, diese sind dem Arbeitnehmer jederzeit zur Einsicht zur Verfügung zu stellen.</p>
                                <p class="text-justify">(2) Der Arbeitgeber kann eine verhältnismäßige Kleiderordnung bestimmen. Sind hohe finanzielle Aufwände hierfür nötig, hat der Arbeitgeber verhältnismäßig Anteile zu übernehmen.</p>
                            </div>
                            <div id="s-p-15">
                                <h6 class="text-center fw-bold my-4" id="p-15" data-added-date="12.07.2023">§ 15<span style="display:none"> - </span><br>Sorgfalts- und Fürsorgepflichten</h6>
                                <p class="text-justify">(1) Der Arbeitnehmer hat mit Sorgfalt die Arbeit zu verrichten. Er ist für entstandenen Schaden nur dann selbst haftbar, wenn er diesen zumindest leichtfertig verschuldet hat. Die Schadenshaftung geht in der Regel nur bei Vorsatz vollständig auf den Arbeitnehmer über.</p>
                                <p class="text-justify">(2) Der Arbeitgeber hat für seinen Arbeitnehmer Fürsorge zu pflegen, insbesondere durch Regelung von Pausen, Verpflegung und Bestimmung von Arbeitsschutzmitteln.</p>
                            </div>
                            <div id="s-p-16">
                                <h6 class="text-center fw-bold my-4" id="p-16" data-added-date="12.07.2023">§ 16<span style="display:none"> - </span><br>Arbeitsvertrag</h6>
                                <p class="text-justify">(1) Wer einen Arbeitnehmer anstellt, hat einen Arbeitsvertrag, schriftlich, mit beidseitiger Einwilligung auszufertigen.</p>
                                <p class="text-justify">(2) Der Arbeitsvertrag muss folgende Angaben enthalten:</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Name des Arbeitgebers im Handels-/Gewerberegister,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Name des Arbeitgebervertreters und dessen Funktion,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">3.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Name und Geburtsdatum des Arbeitnehmers,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">4.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Tätigkeitsbeschreibung,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">5.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Tätigkeitsort, und</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">6.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Höhe und Ausbezahlungsinformationen zur Vergütung.</p>
                                    </dd>
                                </dl>
                                <p class="text-justify">(3) Der Arbeitsvertrag kann weitere Angaben zum Arbeitsverhältnis aufführen und bestimmen.</p>
                                <p class="text-justify">(4) Die Übertretung gesetzlicher Vorschriften ist unzulässig.</p>
                            </div>
                            <div id="s-p-17">
                                <h6 class="text-center fw-bold my-4" id="p-17" data-added-date="12.07.2023">§ 17<span style="display:none"> - </span><br>Aufhebungsvertrag</h6>
                                <p class="text-justify">(1) Wer ein Arbeitsverhältnis außervertraglich und mit beidseitiger Einwilligung beenden will, hat einen Aufhebungsvertrag schriftlich, mit beidseitiger Einwilligung auszufertigen.</p>
                                <p class="text-justify">(2) Der Aufhebungsvertrag muss folgende Angaben enthalten:</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Name des Arbeitgebers im Handels-/Gewerberegister,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Name des Arbeitgebervertreters und dessen Funktion,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">3.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Name und Geburtsdatum des Arbeitnehmers,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">4.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Datum des letzten Arbeitstages, und</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">5.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Höhe und Ausbezahlungsinformationen zur Abfindung.</p>
                                    </dd>
                                </dl>
                                <p class="text-justify">(3) Es liegt keine gesetzliche Vorschrift über die Höhe der Abfindung des Arbeitnehmers vor, diese ist verhältnismäßig festzusetzen. Eine arbeitnehmerseitige Abfindung ist unzulässig.</p>
                            </div>
                            <div id="s-p-18">
                                <h6 class="text-center fw-bold my-4" id="p-18" data-added-date="12.07.2023">§ 18<span style="display:none"> - </span><br>Arbeitszeugnis</h6>
                                <p class="text-justify">(1) Der Arbeitgeber hat auf Forderung des Arbeitnehmers ein Arbeitszeugnis auszustellen, wenn</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Das Arbeitsverhältnis beendet wird, oder</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Die letzte Ausstellung eines solchen Arbeitszeugnisses über sechs Wochen zurückliegt.</p>
                                    </dd>
                                </dl>
                                <p class="text-justify">(2) Weitere Forderungen des Arbeitnehmers über die Ausstellungen eines Arbeitszeugnisses sind für den Arbeitgeber nicht verpflichtend.</p>
                                <p class="text-justify">(3) Ein ausgestelltes Arbeitszeugnis darf nur dem Arbeitnehmer direkt ausgehändigt werden, eine Übergabe oder Sichtung durch andere als den Arbeitgeber oder den Betroffenen selbst ist unzulässig.</p>
                                <p class="text-justify">(4) Die Entscheidung über die Ausstellung eines einfachen oder qualifizierten Arbeitszeugnisses obliegt dem Arbeitnehmer.</p>
                                <p class="text-justify">(5) Wird ein Arbeitszeugnis ausgestellt, muss der Inhalt dieses Zeugnisses der vollständigen Wahrheit entsprechen.</p>
                                <p class="text-justify">(6) Ein einfaches Arbeitszeugnis gibt Auskunft über</p>
                                <dl>
                                    <dt style="float: left; min-width: 1em">1.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Name und Geburtsdatum des Arbeitnehmers,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">2.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Beginn des Arbeitsverhältnisses,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">3.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Ende des Arbeitsverhältnisses,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">4.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Name des Unternehmens,</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">5.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Tätigkeit des Arbeitnehmers, und</p>
                                    </dd>
                                    <dt style="float: left; min-width: 1em">6.</dt>
                                    <dd style="margin-left: 2.5em; margin-bottom: 3ex">
                                        <p class="text-justify">Name der ausstellenden Person und deren Funktion.</p>
                                    </dd>
                                </dl>
                                <p class="text-justify">(7) Ein qualifizierendes Arbeitszeugnis gibt zusätzlich zu den Angaben aus Abs. 6 die Kenntnisse und Leistungen des Arbeitnehmers im Tätigkeitsbereich an.</p>
                            </div>
                            <div id="s-p-19">
                                <h6 class="text-center fw-bold my-4" id="p-19" data-added-date="12.07.2023">§ 19<span style="display:none"> - </span><br>Nachweispflichten</h6>
                                <p class="text-justify">(1) Zur Nachweisbarkeit ausgestellter Dokumente sind Arbeitgeber dazu verpflichtet ausgestellte Dokumente für mindestens drei Monate zu archivieren.</p>
                                <p class="text-justify">(2) Auch im Nachhinein aktualisierte Dokumente sind in allen Versionen fristgerecht zu archivieren.</p>
                                <p class="text-justify">(3) Ebenfalls sind Arbeitgeber auf Verlangen der Aufsichtsbehörde dazu verpflichtet diese Dokumente vorzuzeigen.</p>
                            </div>
                            <div id="s-p-20">
                                <h6 class="text-center fw-bold my-4" id="p-20" data-added-date="12.07.2023">§ 20<span style="display:none"> - </span><br>Meldepflichten</h6>
                                <p class="text-justify">(1) Änderungen der geschäftsführenden Personen sind der Aufsichtsbehörde unmittelbar mitzuteilen. Die zu meldenden Daten sind § 3 Abs. 1 Nr. 4 zu entnehmen.</p>
                                <p class="text-justify">(2) Prokuristen sind der Aufsichtsbehörde spätestens drei Tage nach vertraglicher Festlegung mitzuteilen. Die zu meldenden Daten sind § 3 Abs. 1 Nr. 4 zu entnehmen.</p>
